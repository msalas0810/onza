// Generate row types from the actual migration, using PostgreSQL in WASM.
// For a live Supabase project use npm run db:types instead.
import { format } from "prettier";
import { PGlite } from "@electric-sql/pglite";
import { readFileSync, writeFileSync } from "node:fs";
const db = new PGlite();
await db.exec(
  `create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql as $$select null::uuid$$;create function auth.jwt() returns jsonb language sql as $$select '{}'::jsonb$$;`,
);
await db.exec(
  readFileSync("supabase/migrations/202611150001_core.sql", "utf8"),
);
await db.exec(
  readFileSync("supabase/migrations/202611150003_platform.sql", "utf8"),
);
const { rows } = await db.query(
  `select table_name,column_name,data_type,is_nullable,column_default from information_schema.columns where table_schema='public' order by table_name,ordinal_position`,
);
const groups = Object.groupBy(rows, (r) => r.table_name);
let output = `// Generated by scripts/generate-db-types.mjs from versioned SQL. Do not edit.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: { Tables: {\n`;
for (const [table, columns] of Object.entries(groups)) {
  const tsType = (c) =>
    (({
      integer: "number",
      bigint: "number",
      boolean: "boolean",
      jsonb: "Json",
    })[c.data_type] ?? "string") + (c.is_nullable === "YES" ? " | null" : "");
  output += `${table}: { Row: {${columns.map((c) => `${c.column_name}: ${tsType(c)}`).join(";")}}; Insert: {${columns.map((c) => `${c.column_name}${c.column_default || c.is_nullable === "YES" ? "?" : ""}: ${tsType(c)}`).join(";")}}; Update: {${columns.map((c) => `${c.column_name}?: ${tsType(c)}`).join(";")}}; Relationships: [] };\n`;
}
output += `}; Views: Record<never, never>; Functions: { order_list: { Args: { venue_filter?: string; order_filter?: string; before_time?: string }; Returns: Json }; has_platform_access: { Args: Record<never,never>; Returns: boolean }; platform_command: { Args: { input: Json }; Returns: Json }; onza_command: { Args: { input: Json }; Returns: Json }; sweep_orders: { Args: Record<never,never>; Returns: number }; has_venue_access: { Args: { venue: string; admin_only?: boolean }; Returns: boolean }; venue_summary: { Args: { venue: string; day: string }; Returns: Json }; business_date_at: { Args: { instant: string }; Returns: string } }; Enums: Record<never,never>; CompositeTypes: Record<never,never> } };\n`;
writeFileSync(
  "src/lib/supabase/database.generated.ts",
  await format(output, { parser: "typescript" }),
);
await db.close();
